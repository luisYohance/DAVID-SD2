// Mini-activity1
// Using prompt convert Celcius to Kelvin
// Present the output using alert

let celsius = parseFloat(prompt("Enter the temperature in Celcius: "));
alert(celsius + "C is equal to " + (celsius + 273.15) + "K");

// Mini-activity2
// Using prompt get circle area
// Present the output using alert

let PI = 3.14159;
let radius = parseFloat(prompt("Enter the radius of the circle: "));
alert("The area of the circle is: " + PI * radius * radius);
